/** Prefer content language; Free only TR/EN — others fall back to EN. */
const PACKS = { en: EN, tr: TR };

export function uiFor(lang) {
  const code = String(lang || "en").toLowerCase().slice(0, 2);
  return PACKS[code] || PACKS.en;
}

export function tabsFor(lang) {
  const ui = uiFor(lang);
  return [
    { id: "generate", label: ui.tabs.generate },
    { id: "seo", label: ui.tabs.seo },
    { id: "media", label: ui.tabs.media },
    { id: "images", label: ui.tabs.images },
    { id: "brand", label: ui.tabs.brand },
    { id: "bulk", label: ui.tabs.bulk },
    { id: "plans", label: ui.tabs.plans },
    { id: "assistant", label: ui.tabs.assistant },
  ];
}

export function planCopy(planId, lang) {
  const ui = uiFor(lang);
  return ui.plans[planId] || ui.plans.free;
}
